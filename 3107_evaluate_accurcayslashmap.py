# Reverse lookup: String Name -> Canonical Dataset ID
CANONICAL_NAME_TO_ID = {name: idx for idx, name in DATASET_COCO_CLASSES.items()}

def translate_labels_to_canonical(labels_tensor, source_dict, target_lookup, device):
    """Converts a tensor of predicted IDs to canonical dataset IDs using names as the bridge."""
    if len(labels_tensor) == 0:
        return labels_tensor
    
    translated = []
    for label_id in labels_tensor:
        obj_name = source_dict[label_id.item()]
        new_id = target_lookup[obj_name]
        translated.append(new_id)
        
    return torch.tensor(translated, dtype=torch.long, device=device)

def main():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Calculating mAP Accuracy on: {device.type.upper()}")

    # 1. Load Validation Dataset
    dataset = CustomYOLODataset("./coco5k/images/val", "./coco5k_68/labels/val", target_size=640)
    dataloader = DataLoader(dataset, batch_size=4, shuffle=False, collate_fn=custom_collate_fn)

    # 2. Load Model & Custom Weights
    config = RTDetrV2Config(num_labels=80)
    model = RTDetrV2ForObjectDetection(config)
    
    weights_path = "phase_1_weights_3107_coco5k_68.pth"
    print(f"Loading weights from: {weights_path}")
    
    if not os.path.exists(weights_path):
        print(f"Error: Could not find {weights_path}")
        return
        
    model.load_state_dict(torch.load(weights_path, map_location=device, weights_only=True), strict=True)
    model.to(device)
    model.eval()

    # 3. Initialize the mAP Metric Calculator
    metric = MeanAveragePrecision(box_format='xyxy', class_metrics=False)

    print("\nRunning inferences and computing overlaps... This may take a few minutes.")
    
    with torch.no_grad():
        for batch_idx, (images, targets) in enumerate(dataloader):
            images = images.to(device)
            outputs = model(images)
            
            probs = torch.sigmoid(outputs["logits"])
            pred_boxes = outputs["pred_boxes"]

            formatted_preds = []
            formatted_targets = []

            for i in range(len(images)):
                # --- Format Predictions ---
                scores, labels = probs[i].max(dim=-1)
                
                keep = scores > 0.05
                filtered_scores = scores[keep]
                filtered_labels = labels[keep]
                filtered_boxes = pred_boxes[i][keep]

                # TRANSLATE PREDICTIONS: Custom ID -> Object Name -> Canonical Dataset ID
                filtered_labels = translate_labels_to_canonical(
                    filtered_labels, 
                    CUSTOM_MODEL_CLASSES, 
                    CANONICAL_NAME_TO_ID, 
                    device
                )

                if len(filtered_boxes) > 0:
                    filtered_boxes = box_convert(filtered_boxes, in_fmt="cxcywh", out_fmt="xyxy") * 640
                else:
                    filtered_boxes = torch.empty((0, 4), device=device)

                formatted_preds.append({
                    "boxes": filtered_boxes,
                    "scores": filtered_scores,
                    "labels": filtered_labels,
                })

                # --- Format Ground Truth Targets ---
                tgt_labels = targets[i]["labels"].to(device)
                tgt_boxes = targets[i]["boxes"].to(device)
                
                if len(tgt_boxes) > 0:
                    tgt_boxes = box_convert(tgt_boxes, in_fmt="cxcywh", out_fmt="xyxy") * 640
                else:
                    tgt_boxes = torch.empty((0, 4), device=device)

                formatted_targets.append({
                    "boxes": tgt_boxes,
                    "labels": tgt_labels,
                })

            metric.update(formatted_preds, formatted_targets)
            
            if (batch_idx + 1) % 50 == 0:
                print(f"Processed {batch_idx + 1}/{len(dataloader)} batches...")

    # 4. Compute Final Results
    print("\nFinalizing mAP calculations...")
    results = metric.compute()
    
    print("\n" + "="*45)
    print("=== FINAL ACCURACY METRICS (COCO Standard) ===")
    print("="*45)
    print(f"mAP (IoU=0.50:0.95): {results['map'].item():.4f}  <-- Overall Quality")
    print(f"mAP (IoU=0.50):      {results['map_50'].item():.4f}  <-- Standard Detection")
    print(f"mAP (IoU=0.75):      {results['map_75'].item():.4f}  <-- Strict Detection")
    print(f"mAP (Small objects): {results['map_small'].item():.4f}")
    print(f"mAP (Large objects): {results['map_large'].item():.4f}")
    print("="*45)

if __name__ == "__main__":
    main()